/**
 * Emit the web's half of the token layer from the one place that owns it.
 *
 * `app/src/index.css` used to hold its own copy of the palette and `mobile/src/ui/theme.ts`
 * held another, and `palette.test.ts` existed to notice when they disagreed. It found six
 * of seven already drifted. Noticing drift is a weaker contract than not having two
 * copies, so this generates one from the other and a guard byte-compares the result.
 *
 * Three things come out, and they are three because Tailwind cannot express all of it:
 *
 * 1. `:root` custom properties, with a light block. Tailwind v4's `@theme` is a single
 *    set and cannot itself hold two themes, so the values live in plain custom properties
 *    and `@theme` points at them.
 * 2. A `@theme` block mapping those into Tailwind's own namespaces, so `bg-ground-raised`,
 *    `rounded-plate` and `p-s8` become generated utilities rather than arbitrary values.
 * 3. Plain custom properties for motion and stacking, which Tailwind has no namespace for.
 *
 *   node scripts/tokens-to-css.mjs           # write
 *   node scripts/tokens-to-css.mjs --check   # exit 1 if the file on disk is stale
 */
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import {
  color, label, space, size, radius, text, weight, type,
  border, duration, reduced, stagger, reducedStagger, linger, easing, z,
} from '../core/src/tokens.ts';

const ROOT = resolve(import.meta.dirname, '..');
const OUT = resolve(ROOT, 'app/src/tokens.generated.css');

/** `groundRaised` -> `ground-raised`, one place, used for both directions. */
const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

const lines = [];
const w = (s = '') => lines.push(s);

w('/*');
w(' * Generated by scripts/tokens-to-css.mjs from core/src/tokens.ts. Do not edit.');
w(' *');
w(' * app/src/ui/tokens.generated.test.ts regenerates this in memory and byte-compares, so');
w(' * a hand edit here fails the build rather than quietly becoming the eighth palette.');
w(' */');
w();

/** 1 — the values, as plain custom properties, in two themes. */
const swatches = (theme) => {
  const out = [];
  for (const [name, hex] of Object.entries(color[theme])) out.push(`  --${kebab(name)}: ${hex};`);
  label[theme].forEach((hex, i) => out.push(`  --label-${i}: ${hex};`));
  return out;
};

w(':root {');
lines.push(...swatches('dark'));
w('}');
w();
w('/*');
w(' * Light is an override rather than a second set, because a token that exists in one');
w(' * theme and not the other is how a screen ends up unstyled in exactly one of them.');
w(' *');
w(' * It applies ONLY under an explicit data-theme, never from prefers-color-scheme.');
w(' * This app is dark by decision rather than by preference — the premise of Watching');
w(' * Mode is a dark room with the television on — and the token spec says to land both');
w(' * tables and consume dark only.');
w(' *');
w(' * The first version of this file honoured prefers-color-scheme, and the check that');
w(' * reads colour off the pixels caught it within a minute: in a browser set to light,');
w(' * the new tokens flipped and the legacy seven did not, because they have no light');
w(' * value. Not a light theme — half of one, on top of the other.');
w(' */');
w(':root[data-theme=\'light\'] {');
lines.push(...swatches('light'));
w('}');
w();

/** 2 — Tailwind's namespaces, pointed at the properties above. */
w('@theme {');
for (const name of Object.keys(color.dark)) w(`  --color-${kebab(name)}: var(--${kebab(name)});`);
label.dark.forEach((_, i) => w(`  --color-label-${i}: var(--label-${i});`));
w('');
for (const [name, px] of Object.entries(space)) w(`  --spacing-${name}: ${px}px;`);
for (const [name, px] of Object.entries(size)) w(`  --spacing-${name}: ${px}px;`);
w('');
for (const [name, px] of Object.entries(text)) w(`  --text-${name}: ${px}px;`);
for (const [name, value] of Object.entries(weight)) w(`  --font-weight-${name}: ${value};`);
w('');
for (const [name, px] of Object.entries(radius)) w(`  --radius-${name}: ${px}px;`);
w('');
for (const [name, px] of Object.entries(border)) w(`  --border-width-${kebab(name)}: ${px}px;`);
w('}');
w();

/**
 * 2b — the faces, and the files behind them.
 *
 * `@font-face` here rather than a `<link>` to Google: the phone bundles its faces because
 * "fully offline" is load-bearing, and a web app that reaches for a font over the network
 * is the same app failing on the same plane. One set of files, in `assets/fonts/`, copied
 * into `app/public/fonts/` by this script — the same generate-and-compare shape the palette
 * uses, rather than a second copy somebody has to keep in step.
 *
 * `font-display: block`, not `swap`. Swap paints in the system face and then reflows every
 * heading on this design's tracked caps, which is a worse first second than a short wait on
 * a 587 KB set served from the same origin.
 */
const faces = Object.values(type.family).filter((f) => f.name);
w('/* The faces, bundled rather than fetched — see core/src/tokens.ts. */');
for (const face of faces) {
  const family = face.stack.split(',')[0].replace(/'/g, '').trim();
  const italic = /Italic/.test(face.name);
  const bold = /Bold/.test(face.name);
  const semi = /SemiBold/.test(face.name);
  const medium = /Medium/.test(face.name);
  w('@font-face {');
  w(`  font-family: '${family}';`);
  w(`  src: url('/fonts/${face.name}.ttf') format('truetype');`);
  w(`  font-weight: ${bold && !semi ? 700 : semi ? 600 : medium ? 500 : 400};`);
  w(`  font-style: ${italic ? 'italic' : 'normal'};`);
  w('  font-display: block;');
  w('}');
}
w();
w('@theme {');
for (const [name, face] of Object.entries(type.family)) {
  w(`  --font-${kebab(name)}: ${face.stack};`);
}
w('}');
w();

/** 3 — what Tailwind has no namespace for. */
w('/* Motion and stacking: no Tailwind namespace, so plain properties. */');
w(':root {');
for (const [name, ms] of Object.entries(duration)) w(`  --duration-${kebab(name)}: ${ms}ms;`);
for (const [name, ms] of Object.entries(stagger)) w(`  --stagger-${kebab(name)}: ${ms}ms;`);
for (const [name, ms] of Object.entries(linger)) w(`  --linger-${kebab(name)}: ${ms}ms;`);
for (const [name, fn] of Object.entries(easing)) w(`  --ease-${kebab(name)}: ${fn};`);
for (const [name, order] of Object.entries(z)) w(`  --z-${kebab(name)}: ${order};`);
w('}');
w();
w('/*');
w(' * Reduce Motion is a parallel set with the same names, never a media query wrapped');
w(' * round a call site — the same reason the phone reads a table instead of a ternary.');
w(' */');
w('@media (prefers-reduced-motion: reduce) {');
w('  :root {');
for (const [name, ms] of Object.entries(reduced)) w(`    --duration-${kebab(name)}: ${ms}ms;`);
for (const [name, ms] of Object.entries(reducedStagger)) w(`    --stagger-${kebab(name)}: ${ms}ms;`);
w('  }');
w('}');
w();

/**
 * The faces the web serves, copied rather than duplicated by hand.
 *
 * `assets/fonts/` is the one copy; the phone's bundler reaches it directly and the web
 * needs them under `public/`. Byte-compared on `--check`, like the stylesheet, so a face
 * that changes in one place and not the other fails the build rather than shipping.
 */
const FONTS_FROM = resolve(ROOT, 'assets/fonts');
const FONTS_TO = resolve(ROOT, 'app/public/fonts');

function copyFonts() {
  mkdirSync(FONTS_TO, { recursive: true });
  for (const file of readdirSync(FONTS_FROM)) copyFileSync(`${FONTS_FROM}/${file}`, `${FONTS_TO}/${file}`);
}

function staleFonts() {
  const want = readdirSync(FONTS_FROM);
  let have = [];
  try {
    have = readdirSync(FONTS_TO);
  } catch {
    return want;
  }
  return want.filter(
    (file) =>
      !have.includes(file) ||
      !readFileSync(`${FONTS_FROM}/${file}`).equals(readFileSync(`${FONTS_TO}/${file}`)),
  );
}

export const css = lines.join('\n');

if (process.argv[1] === new URL(import.meta.url).pathname) {
  if (process.argv.includes('--check')) {
    const onDisk = readFileSync(OUT, 'utf8');
    if (onDisk !== css) {
      console.error(`${OUT} is stale. Run: node scripts/tokens-to-css.mjs`);
      process.exit(1);
    }
    const stale = staleFonts();
    if (stale.length) {
      console.error(`${FONTS_TO} is stale for: ${stale.join(', ')}. Run: node scripts/tokens-to-css.mjs`);
      process.exit(1);
    }
    console.log('tokens.generated.css is current');
  } else {
    writeFileSync(OUT, css);
    console.log(`wrote ${OUT} — ${css.split('\n').length} lines`);
    copyFonts();
    console.log(`copied ${readdirSync(FONTS_FROM).length} faces into ${FONTS_TO}`);
  }
}
